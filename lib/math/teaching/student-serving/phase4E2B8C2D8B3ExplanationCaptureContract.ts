/**
 * DREAMSCAPE ONE — Phase 4E-2B-8C-2D.8B-3.
 * Offline PRIVATE explanation-generation/capture CONTRACT ONLY.
 *
 * No AI invocation, API route, database access, file writes or approval.
 * An object matching the B2 mapping shape is NOT proof of staff identity or
 * source authenticity. An authenticated, source-fresh server workflow must
 * re-establish provenance immediately before any future provider call.
 *
 * The output validator only checks STRUCTURE. It cannot determine whether
 * the reasoning, arithmetic or final answer is correct; it cannot validate
 * rendered diagrams or attest that the text was really generated by NOVA.
 */

export const SPECIALIST_CAPTURE_CONTRACT_VERSION = '8C2D8B3.v1' as const;
export const AUTHORING_MAPPING_VERSION = '8C2D8B2.v1' as const;

type UnknownRecord = Record<string, unknown>;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const isRecord = (x: unknown): x is UnknownRecord => x !== null && typeof x === 'object' && !Array.isArray(x);
const exactKeys = (x: UnknownRecord, expected: readonly string[]): boolean =>
  Object.keys(x).length === expected.length && Object.keys(x).every(k => expected.includes(k));
const text = (v: unknown, min: number, max: number): v is string =>
  typeof v === 'string' && v.trim() === v && v.length >= min && v.length <= max &&
  !/[\x00-\x08\x0b\x0c\x0e-\x1f]/.test(v) && !/<\s*\/?\s*[a-z][^>]*>/i.test(v);

const METHODS = {
  'heuristic.multi_step.equal_spacing_interval_count': {
    levels: [3, 4, 5, 6],
    stages: ['represent_positions', 'count_intervals', 'calculate_distance', 'check_small_case'],
  },
  'heuristic.multi_step.multiplicative_comparison_chain': {
    levels: [4, 5, 6],
    stages: ['identify_reference', 'equivalent_units', 'find_one_unit', 'scale_target', 'check_comparisons'],
  },
  'ratio.relationship.before_after_change': {
    levels: [5, 6],
    stages: ['identify_quantities', 'represent_before', 'apply_changes', 'enforce_after_ratio', 'solve_and_verify'],
  },
} as const;

export type SpecialistMethodId = keyof typeof METHODS;
export type CaptureBlockReason =
  | 'INPUT_CONTRACT_INVALID'
  | 'QUESTION_MAPPING_NOT_ELIGIBLE'
  | 'UNSUPPORTED_METHOD_OR_LEVEL'
  | 'OUTPUT_NOT_STRUCTURED'
  | 'OUTPUT_IDENTITY_MISMATCH'
  | 'OUTPUT_STAGE_MISMATCH'
  | 'OUTPUT_CONTENT_INVALID';
export type SafeCaptureBlock = Readonly<{
  status: 'blocked'; reasonCode: CaptureBlockReason;
  providerInvocationAllowed: false; learnerReleaseAllowed: false;
}>;
const blocked = (reasonCode: CaptureBlockReason): SafeCaptureBlock => Object.freeze({
  status: 'blocked' as const, reasonCode, providerInvocationAllowed: false as const,
  learnerReleaseAllowed: false as const,
});

/** Strictly descriptive. It does NOT carry question text or an answer key. */
export type PrivateExplanationContract = Readonly<{
  status: 'offline_contract_ready_capture_disabled';
  schemaVersion: typeof SPECIALIST_CAPTURE_CONTRACT_VERSION;
  questionId: string;
  questionVersion: number;
  primaryLevel: number;
  methodId: SpecialistMethodId;
  requiredStages: readonly string[];
  sourceAuthenticated: false;
  sourceFingerprintVerified: false;
  providerInvocationAllowed: false;
  captureStored: false;
  mathematicallyVerified: false;
  humanApproved: false;
  learnerReleaseAllowed: false;
}>;
export type PrivateExplanationInputResult = SafeCaptureBlock | PrivateExplanationContract;

/**
 * Accepts only the narrow *data shape* created in 8B-2. The caller MUST
 * never substitute this check for an authenticated staff source re-read.
 * Does not return question prose; answers, sessions and all extra fields
 * are rejected. No outbound model request is constructed.
 */
export function inspectOfflineSpecialistExplanationInput(
  mapped: unknown, proposedMethodId: unknown,
): PrivateExplanationInputResult {
  if (!isRecord(mapped) || !exactKeys(mapped, [
    'status', 'mappingVersion', 'sourceVersion', 'privateDraft',
    'providerInvocationAllowed', 'learnerReleaseAllowed',
  ]) || mapped.status !== 'mapped_private_only' ||
      mapped.mappingVersion !== AUTHORING_MAPPING_VERSION ||
      mapped.providerInvocationAllowed !== false || mapped.learnerReleaseAllowed !== false ||
      !Number.isSafeInteger(mapped.sourceVersion) || (mapped.sourceVersion as number) < 1 ||
      !isRecord(mapped.privateDraft)) return blocked('INPUT_CONTRACT_INVALID');

  const draft = mapped.privateDraft;
  if (!exactKeys(draft, [
    'id', 'subject', 'primary_level', 'topic_title', 'skill', 'difficulty',
    'question_type', 'instruction', 'prompt', 'content', 'answer_data',
    'correct_answer', 'explanation',
  ]) || !UUID.test(String(draft.id)) || draft.subject !== 'math' ||
      draft.answer_data !== null || draft.correct_answer !== null ||
      draft.explanation !== null || !isRecord(draft.content) ||
      Object.keys(draft.content).length !== 0 ||
      !text(draft.prompt, 10, 1500) || !text(draft.instruction, 0, 400) ||
      !text(draft.topic_title, 0, 160) || !text(draft.skill, 0, 160) ||
      !Number.isInteger(draft.primary_level) ||
      !(draft.difficulty === null || (Number.isInteger(draft.difficulty) &&
          (draft.difficulty as number) >= 1 && (draft.difficulty as number) <= 5)) ||
      typeof draft.question_type !== 'string' ||
      !['open_ended','short_answer','numeric','numeric_unit','fraction','money','short_text','fill_blank'].includes(draft.question_type))
    return blocked('QUESTION_MAPPING_NOT_ELIGIBLE');

  if (typeof proposedMethodId !== 'string' || !Object.prototype.hasOwnProperty.call(METHODS, proposedMethodId))
    return blocked('UNSUPPORTED_METHOD_OR_LEVEL');
  const methodId = proposedMethodId as SpecialistMethodId;
  if (!(METHODS[methodId].levels as readonly number[]).includes(draft.primary_level as number))
    return blocked('UNSUPPORTED_METHOD_OR_LEVEL');

  return Object.freeze({
    status: 'offline_contract_ready_capture_disabled' as const,
    schemaVersion: SPECIALIST_CAPTURE_CONTRACT_VERSION,
    questionId: draft.id as string,
    questionVersion: mapped.sourceVersion as number,
    primaryLevel: draft.primary_level as number,
    methodId,
    requiredStages: Object.freeze([...METHODS[methodId].stages]) as readonly string[],
    sourceAuthenticated: false as const,
    sourceFingerprintVerified: false as const,
    providerInvocationAllowed: false as const,
    captureStored: false as const,
    mathematicallyVerified: false as const,
    humanApproved: false as const,
    learnerReleaseAllowed: false as const,
  });
}

/** Metadata-only, safe to report to a staff audit. No generated prose. */
export type PrivateExplanationStructureResult = SafeCaptureBlock | Readonly<{
  status: 'structure_valid_review_pending';
  schemaVersion: typeof SPECIALIST_CAPTURE_CONTRACT_VERSION;
  methodId: SpecialistMethodId;
  stepCount: number;
  hasDiagramPlan: boolean;
  hasMathWorking: boolean;
  originalGenerationVerified: false;
  sourceFreshnessVerified: false;
  mathematicallyVerified: false;
  visualsRenderedVerified: false;
  educatorApproved: false;
  captureStored: false;
  providerInvocationAllowed: false;
  learnerReleaseAllowed: false;
}>;

/**
 * Inspect an UNTRUSTED, already-produced object. Does not save it or copy any
 * text into return values. Accepting shape != proving maths or provenance.
 * The only allowable visual plan is descriptive metadata, not an SVG asset.
 */
export function inspectOfflineSpecialistExplanationStructure(
  contract: unknown, proposedOutput: unknown,
): PrivateExplanationStructureResult {
  if (!isRecord(contract) || contract.status !== 'offline_contract_ready_capture_disabled' ||
      contract.schemaVersion !== SPECIALIST_CAPTURE_CONTRACT_VERSION ||
      contract.providerInvocationAllowed !== false || contract.learnerReleaseAllowed !== false ||
      contract.sourceAuthenticated !== false || contract.sourceFingerprintVerified !== false ||
      !UUID.test(String(contract.questionId)) || !Number.isSafeInteger(contract.questionVersion) ||
      (contract.questionVersion as number) < 1 || typeof contract.methodId !== 'string' ||
      !Object.prototype.hasOwnProperty.call(METHODS, contract.methodId) ||
      !Array.isArray(contract.requiredStages) ||
      JSON.stringify(contract.requiredStages) !== JSON.stringify(METHODS[contract.methodId as SpecialistMethodId].stages))
    return blocked('INPUT_CONTRACT_INVALID');

  if (!isRecord(proposedOutput) || !exactKeys(proposedOutput, [
    'schemaVersion', 'questionId', 'questionVersion', 'methodId',
    'steps', 'finalAnswer', 'finalCheck', 'visualPlan',
  ]) || proposedOutput.schemaVersion !== SPECIALIST_CAPTURE_CONTRACT_VERSION ||
      !Array.isArray(proposedOutput.steps) || !isRecord(proposedOutput.visualPlan))
    return blocked('OUTPUT_NOT_STRUCTURED');

  if (proposedOutput.questionId !== contract.questionId ||
      proposedOutput.questionVersion !== contract.questionVersion ||
      proposedOutput.methodId !== contract.methodId)
    return blocked('OUTPUT_IDENTITY_MISMATCH');

  const stages = METHODS[contract.methodId as SpecialistMethodId].stages as readonly string[];
  if (proposedOutput.steps.length !== stages.length || proposedOutput.steps.some((s, i) =>
      !isRecord(s) || !exactKeys(s, ['stageId','explanation','working']) || s.stageId !== stages[i]))
    return blocked('OUTPUT_STAGE_MISMATCH');

  if (proposedOutput.steps.some(s => {
      const x = s as UnknownRecord;
      return !text(x.explanation, 20, 900) || !text(x.working, 0, 500);
    }) || !proposedOutput.steps.some(s => typeof s.working === 'string' && s.working.length >= 3) ||
      !text(proposedOutput.finalAnswer, 1, 180) || !text(proposedOutput.finalCheck, 20, 700) ||
      !exactKeys(proposedOutput.visualPlan, ['kind','description']) ||
      !['none','diagram','number_line','bar_model','ratio_table'].includes(String(proposedOutput.visualPlan.kind)) ||
      !text(proposedOutput.visualPlan.description, 0, 500))
    return blocked('OUTPUT_CONTENT_INVALID');

  return Object.freeze({
    status: 'structure_valid_review_pending' as const,
    schemaVersion: SPECIALIST_CAPTURE_CONTRACT_VERSION,
    methodId: contract.methodId as SpecialistMethodId,
    stepCount: stages.length,
    hasDiagramPlan: proposedOutput.visualPlan.kind !== 'none',
    hasMathWorking: true,
    originalGenerationVerified: false as const,
    sourceFreshnessVerified: false as const,
    mathematicallyVerified: false as const,
    visualsRenderedVerified: false as const,
    educatorApproved: false as const,
    captureStored: false as const,
    providerInvocationAllowed: false as const,
    learnerReleaseAllowed: false as const,
  });
}
